-- VvV Messenger security update. Run in Supabase SQL Editor.
-- After creating/signing up the admin account (username=admin), run the
-- final UPDATE statement at the bottom ONCE to grant admin privileges.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9_.-]{3,24}$'),
  display_name text not null default 'کاربر',
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists is_admin boolean not null default false;
alter table public.profiles add column if not exists steam_id text;
alter table public.profiles drop constraint if exists profiles_steam_id_format;
alter table public.profiles add constraint profiles_steam_id_format check (steam_id is null or steam_id ~ '^[0-9]{17}$');

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint messages_no_self_message check (sender_id <> recipient_id)
);
create index if not exists messages_sender_recipient_created on public.messages(sender_id, recipient_id, created_at);
create index if not exists messages_recipient_sender_created on public.messages(recipient_id, sender_id, created_at);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare chosen_username text;
begin
  chosen_username := lower(coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(new.email, '@', 1)));
  insert into public.profiles (id, username, display_name) values (new.id, chosen_username, chosen_username);
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
drop policy if exists "Authenticated users can view profiles" on public.profiles;
create or replace function public.vvv_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin);
$$;
revoke all on function public.vvv_is_admin() from public;
grant execute on function public.vvv_is_admin() to authenticated;

-- User suggestions: users may submit their own suggestions; only admins can read them.
create table if not exists public.suggestions (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists suggestions_created_at_idx on public.suggestions(created_at desc);
alter table public.suggestions enable row level security;
drop policy if exists "Users can submit own suggestions" on public.suggestions;
create policy "Users can submit own suggestions" on public.suggestions for insert to authenticated
with check (auth.uid() = sender_id);
drop policy if exists "Admins can read suggestions" on public.suggestions;
create policy "Admins can read suggestions" on public.suggestions for select to authenticated
using (public.vvv_is_admin());
grant insert, select on public.suggestions to authenticated;

-- Private-server foundation only. RLS is enabled without client policies so this
-- feature remains unavailable until a later release deliberately adds access rules.
create table if not exists public.servers (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 50),
  description text not null default '',
  is_official boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.server_members (
  server_id uuid not null references public.servers(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','moderator','member')),
  joined_at timestamptz not null default now(),
  primary key (server_id,user_id)
);
alter table public.servers enable row level security;
alter table public.server_members enable row level security;

drop policy if exists "Users can view own profile or admin views all" on public.profiles;
create policy "Users can view own profile or admin views all" on public.profiles for select to authenticated
using (auth.uid() = id or public.vvv_is_admin());
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles for update to authenticated
using (auth.uid() = id) with check (auth.uid() = id);
-- Never allow a normal user to promote themselves through profile updates.
revoke update (is_admin) on public.profiles from authenticated;

drop policy if exists "Participants can read messages" on public.messages;
create policy "Participants can read messages" on public.messages for select to authenticated
using (auth.uid() = sender_id or auth.uid() = recipient_id);
drop policy if exists "Users can send messages as themselves" on public.messages;
create policy "Users can send messages as themselves" on public.messages for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> recipient_id);

-- Search returns only matching users. A normal account cannot enumerate all users.
drop function if exists public.search_vvv_users(text);
create function public.search_vvv_users(search_text text)
returns table(id uuid, username text, display_name text, steam_id text)
language sql stable security definer set search_path = '' as $$
  select p.id, p.username, p.display_name, p.steam_id
  from public.profiles p
  where auth.uid() is not null
    and p.id <> auth.uid()
    and length(trim(coalesce(search_text,''))) >= 2
    and p.username ilike '%' || trim(search_text) || '%'
  order by p.username limit 30;
$$;
revoke all on function public.search_vvv_users(text) from public;
grant execute on function public.search_vvv_users(text) to authenticated;

-- Admin-only directory RPC. Returns an empty result to non-admins.
drop function if exists public.admin_vvv_users();
create function public.admin_vvv_users()
returns table(id uuid, username text, display_name text, steam_id text)
language sql stable security definer set search_path = '' as $$
  select p.id, p.username, p.display_name, p.steam_id from public.profiles p
  where public.vvv_is_admin()
  order by p.username;
$$;
revoke all on function public.admin_vvv_users() from public;
grant execute on function public.admin_vvv_users() to authenticated;

